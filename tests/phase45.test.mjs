import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const schema=readFileSync('supabase/migrations/20261114_phase45_individual_compensation.sql','utf8')
const bulk=readFileSync('supabase/migrations/20261114_phase45_bulk_attendance.sql','utf8')
const payroll=readFileSync('supabase/migrations/20261114_phase45_payment_balance.sql','utf8')
const app=readFileSync('src/App.tsx','utf8')
const field=readFileSync('src/FieldDay.tsx','utf8')
const fieldCss=readFileSync('src/field-edition.css','utf8')
const data=readFileSync('src/phase45-data.ts','utf8')
const home=readFileSync('src/HomeEdition.tsx','utf8')
test('Exactly three wage modes, no forfait or mixed pay for a worker/day',()=>{
 assert.match(schema,/mode in \('individual_sacks','daily'\)/)
 assert.match(schema,/unique\(work_day_id,worker_id\)/)
 assert.match(schema,/v_attendance\.group_id is not null/)
 assert.match(schema,/protect_individual_compensation/)
 assert.doesNotMatch(schema,/'forfait'|'flat_fee'/)
})
test('Historical earnings preserved, individual and group sums both apply to payroll',()=>{
 assert.match(payroll,/public\.worker_earnings/)
 assert.match(payroll,/public\.worker_day_compensations/)
 assert.match(schema,/generated always as \(quantity::bigint \* rate_cents::bigint\)/)
 assert.match(schema,/create policy owner_read_individual_pay/)
 assert.match(schema,/grant select on public\.worker_day_compensations to authenticated/)
 assert.doesNotMatch(schema,/drop table|truncate table/i)
})
test('Owner-only atomic bulk attendance supports 100 workers and three actions',()=>{
 assert.match(bulk,/cardinality\(v_distinct\)>100/)
 assert.match(bulk,/auth\.uid\(\)/)
 assert.match(bulk,/p_action not in \('present','absent','assign'\)/)
 assert.match(bulk,/on conflict\(work_day_id,worker_id\) do nothing/)
 assert.match(bulk,/revoke all on function public\.bulk_attendance.*public,anon/)
 assert.match(data,/\.rpc\('bulk_attendance'/)
})
test('Mobile field interface has search, filters, bulk selection and distinct stages',()=>{
 assert.match(app,/<FieldDay\/>/)
 for(const term of ['pointage','groupes','gains','field-search','Sélection multiple','bulkAttendance','WorkerStatusSheet','Sans groupe'])
  assert.match(field,new RegExp(term))
 assert.match(field,/aria-label="Rechercher un ouvrier"/)
 assert.match(fieldCss,/prefers-reduced-motion/)
 assert.match(fieldCss,/safe-area-inset-bottom/)
})
test('Home dashboard uses actual API data, no fabricated placeholder totals',()=>{
 assert.match(app,/<HomeEdition/)
 assert.match(home,/listWorkers\(\)/)
 assert.match(home,/readPayroll\(\)/)
 assert.match(home,/group_harvests/)
 assert.match(home,/worker_day_compensations/)
})
