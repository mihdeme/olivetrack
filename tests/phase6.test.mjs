import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const app=readFileSync('src/App.tsx','utf8')
const source=readFileSync('src/Reports.tsx','utf8')
const data=readFileSync('src/report-data.ts','utf8')
const css=readFileSync('src/report-print.css','utf8')
const mobile=readFileSync('src/mobile-overflow.css','utf8')
test('Four distinct printable report types are wired into Bilans',()=>{
 assert.match(app,/<Reports\/>/)
 for(const type of ['payroll','harvest','buyers','finance'])assert.match(source,new RegExp("kind:'"+type+"'"))
 assert.match(source,/readReportData\(\)/)
 assert.match(source,/window\.print\(\)/)
 assert.match(source,/generated/)
})
test('Printable records use real sources and include daily and collective compensation',()=>{
 for(const table of ['work_days','harvest_groups','attendances','group_harvests','worker_earnings','worker_day_compensations'])
  assert.match(data,new RegExp("'"+table+"'"))
 assert.match(data,/readPayroll\(\)/)
 assert.match(data,/listLedger\(\)/)
 assert.match(data,/listBuyers\(\)/)
 assert.match(data,/listWorkers\(\)/)
 assert.match(data,/pages<GroupEarning>/)
})
test('Paie pays and balances are separated into opening/period/closing amounts',()=>{
 assert.match(data,/opening:e\.before-p\.before/)
 assert.match(data,/closing:e\.before-p\.before\+e\.during-p\.during/)
 assert.match(data,/previous\.before\+=amount/)
 assert.match(data,/previous\.during\+=amount/)
 assert.match(source,/Signature/)
 assert.match(source,/signature:true/)
})
test('Reports never confuse sales with receipts, expenses or cash balances',()=>{
 assert.match(data,/sales:\s*e\.kind\.startsWith\('sale'\)/)
 assert.match(data,/received:\s*e\.kind\.startsWith\('receipt'\)/)
 assert.match(data,/wages:p\.amount_cents/)
 assert.match(source,/Ce n’est ni le résultat comptable ni le solde des espèces/)
})
test('A4 layout has physically fixed pages, page numbers and no split table rows',()=>{
 assert.match(css,/@page\{size:A4 portrait;margin:0\}/)
 assert.match(css,/width:210mm/)
 assert.match(css,/height:295mm/)
 assert.match(css,/break-inside:avoid/)
 assert.match(css,/print-color-adjust:exact/)
 assert.match(css,/report-signatures/)
 assert.match(source,/const size=14/)
 assert.match(source,/Page \{index\+1\} \/ \{pages\.length\}/)
 assert.match(source,/previewScale/)
})
test('Mobile corrections target overflow of date fields and top safe area',()=>{
 assert.match(app,/mobile-overflow\.css/)
 assert.match(mobile,/safe-area-inset-top/)
 assert.match(mobile,/grid-template-columns:repeat\(2,minmax\(0,1fr\)\)/)
 assert.match(mobile,/input\[type=date\]/)
 assert.match(mobile,/overflow-x:clip/)
 assert.match(mobile,/position:sticky;top:0/)
})
