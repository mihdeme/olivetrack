import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const sql=readFileSync('supabase/migrations/20261114_phase5_campaign_ledger.sql','utf8')
const data=readFileSync('src/phase5-data.ts','utf8')
const ui=readFileSync('src/Phase5.tsx','utf8')
const app=readFileSync('src/App.tsx','utf8')
const home=readFileSync('src/HomeEdition.tsx','utf8')

test('Buyers and immutable financial ledger are owner-isolated',()=>{
 for(const table of ['olives_buyers','campaign_ledger'])assert.match(sql,new RegExp('alter table public\\.'+table+' enable row level security'))
 assert.match(sql,/owner_id=\(select auth\.uid\(\)\)/)
 assert.match(sql,/create policy campaign_ledger_owner_read/)
 assert.match(sql,/revoke all on public\.olives_buyers,public\.campaign_ledger from public,anon,authenticated/)
 assert.match(sql,/grant select on public\.campaign_ledger to authenticated/)
 assert.match(sql,/create trigger campaign_ledger_append_only/)
})
test('Each actual financial transaction is distinct from revenue accrual and reversible',()=>{
 assert.match(sql,/kind in \('sale','receipt','expense'/)
 assert.match(sql,/reversal_of uuid null unique/)
 assert.match(sql,/request_id uuid not null unique/)
 assert.match(sql,/v_old\.kind\|\|'_reversal'/)
 assert.match(sql,/v_old\.amount_cents/)
 assert.doesNotMatch(sql,/drop table|truncate table/i)
 assert.match(sql,/public\.reverse_campaign_entry/)
 assert.match(ui,/contrepassation/i)
})
test('Weights are grams, unit prices are integer cents, with exact SQL cent rounding',()=>{
 assert.match(sql,/weight_grams bigint/)
 assert.match(sql,/unit_price_cents integer/)
 assert.match(sql,/round\(p_weight_grams::numeric\*p_unit_price_cents::numeric\/1000\)::bigint/)
 assert.match(sql,/abs\(weight_grams\) between 1 and 1000000000/)
 assert.match(data,/Math\.round\(grams\*priceCents\/1000\)/)
 assert.match(data,/export const parseKg=/)
})
test('Operating expenses exclude salaries, with explicit categories and cash methods',()=>{
 assert.match(sql,/transport','fuel','equipment','maintenance','food','other/)
 assert.match(sql,/method in \('cash','bank','other'\)/)
 assert.doesNotMatch(sql,/forfait|daily_salary/)
 assert.match(data,/expense_reversal/)
 assert.match(ui,/Flux financier net/)
 assert.match(ui,/Ce n’est pas le solde physique des espèces/)
})
test('Phase 5 UI supports buyers, deliveries, receipts, expenses and correction journal',()=>{
 assert.match(app,/<Phase5\/>/)
 for(const term of ['listBuyers','listLedger','createEntry','reverseEntry','Encaissements','Dépenses','Pesées & ventes','Journal','Acheteurs'])
  assert.match(ui,new RegExp(term))
 assert.match(ui,/type="date"/)
 assert.match(ui,/p5-buyers/)
 assert.match(home,/listLedger\(\)/)
 assert.match(home,/Reste à encaisser/)
})
test('No direct insert or destructive edits of immutable ledger exposed to browser',()=>{
 assert.match(data,/\.rpc\('record_campaign_entry'/)
 assert.match(data,/\.rpc\('reverse_campaign_entry'/)
 assert.doesNotMatch(data,/\.from\('campaign_ledger'\)\.(insert|update|delete)/)
 assert.match(sql,/if \(select auth\.uid\(\)\) is distinct from v_owner/)
 assert.match(sql,/revoke all on function public\.record_campaign_entry.*public,anon/)
})
